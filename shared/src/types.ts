/** Sculpted SDF island biome themes. */
export type ThemeId = "emerald_spire" | "canyon_arch" | "twin_pillars";

/** Supported PvP match formats. */
export type GameMode = "ffa" | "2v2";

/** Team assignment identifier (used in 2v2 and lobby setup). */
export type TeamId = "A" | "B";

/** Authoritative state-machine turn phases. */
export type TurnPhase =
  | "LOBBY"
  | "ACTIVE"
  | "RESOLVING"
  | "RETREAT"
  | "DRAFT_IF_READY"
  | "ROUND_DRAFT"
  | "MATCH_OVER";

/** Deterministic terrain subtraction operation applied to the SDF grid. */
export interface CarveOp {
  center: Vec3;
  radius: number;
  shape: "sphere" | "capsule";
  end?: Vec3;
}

/** Deterministic explosion or melee strike event generated by physics simulation. */
export interface ImpactEvent {
  time: number;
  position: Vec3;
  carveOp: CarveOp | null;
  damageRadius: number;
  baseDamage: number;
  knockback: number;
  isSubSpore?: boolean;
  isPull?: boolean;
}

/** Resolved damage, shield absorption, knockback, and KO outcome for one critter. */
export interface CritterHitResult {
  critterId: string;
  damage: number;
  shieldAbsorbed: boolean;
  knockbackVelocity: Vec3;
  newPosition: Vec3;
  newHp: number;
  drowned: boolean;
  knockedOut: boolean;
}

/** Complete deterministic simulation output for a fired artillery/melee shot. */
export interface ShotSimulationResult {
  path: Vec3[];
  durationSec: number;
  impacts: ImpactEvent[];
  carveOps: CarveOp[];
  hits: CritterHitResult[];
}

